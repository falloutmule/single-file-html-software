import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { Buffer } from "node:buffer";
import { packProject } from "@sfhs/packer";

const repositoryRoot = resolve(import.meta.dirname, "..", "..", "..");
const projectRoot = resolve(repositoryRoot, "examples", "control-feedback-demo-shell");
const output = resolve(repositoryRoot, "packages", "control-feedback-exporter", "src", "demo-shell.generated.ts");
const packed = await packProject(projectRoot, { sourceRevision: "control-feedback-demo-shell-v0" });
const source = `// Generated by tools/generate-demo-shell.mjs; do not hand-edit.\nexport const controlFeedbackDemoShellHtml = ${JSON.stringify(Buffer.from(packed.bytes).toString("utf8"))} as const;\nexport const controlFeedbackDemoShellSha256 = ${JSON.stringify(packed.descriptor.artifact.sha256)} as const;\n`;
await writeFile(output, source, "utf8");
process.stdout.write(`${JSON.stringify(packed.descriptor.artifact)}\n`);
