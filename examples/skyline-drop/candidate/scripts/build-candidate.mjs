import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n');
const assetDir = path.join(root, 'public/assets');
fs.mkdirSync(path.join(root, '.candidate'), { recursive: true });
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
execFileSync('tsc', ['-p', path.join(root, 'tsconfig.json')], { stdio: 'inherit' });

let html = read('src/index.html');
const css = read('src/styles.css');
let game = read('.candidate/game.js');
const pixi = read('vendor/pixi.min.js');

const assetPattern = /assets\/[A-Za-z0-9_.-]+\.png/g;
const assetPaths = [...new Set(game.match(assetPattern) ?? [])].sort();
for (const rel of assetPaths) {
  const bytes = fs.readFileSync(path.join(root, 'public', rel));
  const dataUri = `data:image/png;base64,${bytes.toString('base64')}`;
  game = game.split(rel).join(dataUri);
}

const safeScript = (source) => source.replaceAll('</script', '<\\/script');
html = html
  .replace('<html lang="en">', '<html lang="en" data-sfhs-candidate="INTAKE_REQUIRED" data-renderer="pixi-webgl">')
  .replace('  <link rel="stylesheet" href="styles.css">', `  <style>\n${css}\n  </style>`)
  .replace('</body>', `  <script>\n${safeScript(pixi)}\n  </script>\n  <script>\n${safeScript(game)}\n  </script>\n</body>`);

const buildInput = crypto.createHash('sha256')
  .update(css).update('\0').update(pixi).update('\0').update(game).update('\0').update(html)
  .digest('hex');
html = html.replace('</head>', `  <meta name="skyline-drop-build-id" content="candidate-${buildInput.slice(0, 16)}">\n</head>`);
html = html.replace(/\r\n/g, '\n');
const output = path.join(root, 'dist/index.html');
fs.writeFileSync(output, html);
const bytes = fs.statSync(output).size;
const sha256 = crypto.createHash('sha256').update(fs.readFileSync(output)).digest('hex');
const descriptor = {
  schema: 'skyline-drop-candidate@1',
  status: 'INTAKE_REQUIRED',
  renderer: 'PixiJS v8.19.0 / WebGL required',
  output: 'dist/index.html',
  bytes,
  sha256,
  buildId: `candidate-${buildInput.slice(0, 16)}`,
  inlinedAssetCount: assetPaths.length,
  externalRuntimeUrls: [],
  note: 'Generated by bounded candidate pack script because the canonical SFHS CLI was unavailable in this runtime.'
};
fs.writeFileSync(path.join(root, 'evidence/candidate-descriptor.json'), JSON.stringify(descriptor, null, 2) + '\n');
console.log(JSON.stringify(descriptor, null, 2));
