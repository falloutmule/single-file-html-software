import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src", "assets");
const prefix = [0x00,0x61,0x73,0x6d,0x01,0x00,0x00,0x00,0x01,0x07,0x01,0x60,0x02,0x7f,0x7f,0x01,0x7f,0x03,0x02,0x01,0x00,0x07,0x07,0x01,0x03,0x72,0x75,0x6e,0x00,0x00,0x0a,0x09,0x01,0x07,0x00,0x20,0x00,0x20,0x01];
await mkdir(root, { recursive: true });
await Promise.all([["add.wasm", 0x6a], ["multiply.wasm", 0x6c]].map(([name, opcode]) => writeFile(resolve(root, String(name)), Uint8Array.from([...prefix, Number(opcode), 0x0b]))));
